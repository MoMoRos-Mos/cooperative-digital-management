-- 6. แสดงเฉพาะสมาชิกที่มียอดฝากรวม > 10000
SELECT
	m.member_id,
	m.full_name,
	SUM(d.balance) AS Total_Deposit_Amount
FROM members m
JOIN deposit_accounts d
ON m.member_id = d.member_id
GROUP BY m.member_id, m.full_name
HAVING SUM(d.balance) > 10000
ORDER BY Total_Deposit_Amount DESC;

