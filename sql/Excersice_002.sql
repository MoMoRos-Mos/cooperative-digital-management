-- 4. สรุปยอดฝากแยกตาม account_type
-- V1: ลืมนึกว่าข้มูลแยกกกัน 2 Tables
SELECT
	m.member_id,
	m.full_name,
	d.member_id,
	d.account_type,
	SUM(d.balance) AS Total_Deposit_Amount
FROM members m
JOIN deposit_accounts d
ON m.member_id = d.member_id
GROUP BY m.member_id, m.full_name, d.member_id, d.account_type
/* Versoin Fix 2: นึกได้ว่าข้อมูลยอดฝาก / ประเภทบัญชีอยู่ใน deposit_accounts เดียวกันไม่จำเป้นต้อง JOIN
