-- Create Data
CREATE TABLE audit_logs(
	audit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- Log Key / ID

	table_name VARCHAR(50) NOT NULL, -- table log name
	record_id INTEGER NOT NULL, -- ID of record has edit

	record_type VARCHAR(30) NOT NULL, -- INSERT / UPDATE / DELETE

	old_data JSONB, -- old data in json style
	new_data JSONB,-- new data in json style

	changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP -- Edit time
);


-- 2. CREATE FUNCTION audit_loans_changes()
CREATE OR REPLACE FUNCTION audit_loans_changes()
RETURNS TRIGGER
AS $$
BEGIN
	INSERT INTO audit_logs
	(
		table_name,
		record_id,
		record_type,
		old_data,
		new_data,
		changed_by
	)
	VALUES
	(
		'loans',
		NEW.loan_id,
		'UPDATE',
		to_jsonb(OLD),
		to_jsonb(NEW),
		 current_user
	);
	
	RETURN NEW;
END;
$$ LANGUAGE plpgsql;

