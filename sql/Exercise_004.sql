-- 7. ตัวใหม่ที่ต้องเรียน: TG_OP
CREATE OR REPLACE FUNCTION audit_loans_changes()
RETURNS TRIGGER
AS $$
BEGIN

	IF TG_OP = 'INSERT' THEN

	INSERT INTO audit_logs
	(
		table_name,
		record_id,
		record_type,
		old_data,
		new_data,
		changed_by
	)
	VALUES
	(
		TG_TABLE_NAME,
		NEW.loan_id,
		TG_OP,
		 NULL,
		to_jsonb(NEW),
		current_user
	);

	RETURN NEW;
	
	ELSIF TG_OP = 'UPDATE' THEN

	INSERT INTO audit_logs
	(
		table_name,
		record_id,
		record_type,
		old_data,
		new_data,
		changed_by
	)
	VALUES
	(
		TG_TABLE_NAME,
		NEW.loan_id,
		TG_OP,
		to_jsonb(OLD),
		to_jsonb(NEW),
		current_user
	);

	RETURN NEW;
	
	ELSIF TG_OP = 'DELETE' THEN

	INSERT INTO audit_logs
	(
		table_name,
		record_id,
		record_type,
		old_data,
		new_data,
		changed_by
	)
	VALUES
	(
		TG_TABLE_NAME,
		OLD.loan_id,
		TG_OP,
		to_jsonb(OLD),
		 NULL,
		current_user
	);

	RETURN OLD;
	END IF;

END;
$$ LANGUAGE	plpgsql;

-- Connect TRIGGER to Function
CREATE OR REPLACE TRIGGER trg_audit_loan_change
AFTER INSERT OR UPDATE OR DELETE
ON loans
FOR EACH ROW
EXECUTE FUNCTION audit_loans_changes();

