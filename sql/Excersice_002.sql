	m.member_id,
	m.full_name,
	MAX(d.balance) AS Maximum_deposit_amount
FROM members m
JOIN deposit_accounts d
ON m.member_id = d.member_id
GROUP BY m.member_id, m.full_name, d.balance
ORDER BY d.balance DESC;
