SELECT
	SUM(balance) AS Total_Deposit_Amount
FROM deposit_accounts
GROUP BY account_type
ORDER BY balance DESC;
-- V3: ย้อนไปทบทวนวิธีเลือกแสดงผลแบบหมวดหมู่เฉพาะ จนได้ผลลัพธ์ดังนี้
